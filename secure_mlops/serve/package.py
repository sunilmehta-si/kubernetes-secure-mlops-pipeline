"""Package the champion as a KServe "modelcar": an OCI image holding a model bundle under /models.

KServe mounts such an image's /models at /mnt/models next to the server, so the model travels as an image: it can be
pushed to a registry, pinned by digest, signed, and checked by an admission policy like any other image. The bundle
is exported only after the champion's signature verifies; an unsigned champion cannot be packaged.
"""
from __future__ import annotations

import json
import shutil
from pathlib import Path

import mlflow
from mlflow import MlflowClient

from .. import registry
from .bundle import MLBOM, MODEL, RELEASE, SIGNATURE

# busybox:1.37.0, multi-arch index; KServe's modelcar sidecar needs a shell to link /models into the shared volume.
MODELCAR_BASE = "busybox:1.37.0@sha256:bdf57e528e45e4433820e045b29b4597825a1c9e38353532d90a01445013f82e"
DOCKERFILE = f"""# A model packaged as an OCI image for KServe (modelcar). Generated by smlops package.
FROM {MODELCAR_BASE}
COPY {MODEL}/ /models/{MODEL}/
COPY {SIGNATURE} {MLBOM} {RELEASE} /models/
USER 65532:65532
"""


class PackageError(RuntimeError):
    pass


def package(model_name: str, public_key: str | Path, output: str | Path, alias: str = registry.CHAMPION) -> Path:
    version = registry.by_alias(model_name, alias)
    if version is None:
        raise PackageError(f"{model_name} has no {alias} to package")
    registry.load(version, public_key)                      # verifies the stored files, or raises
    out = Path(output)
    if out.exists() and any(out.iterdir()):
        raise PackageError(f"{out} is not empty; refusing to mix bundles")
    out.mkdir(parents=True, exist_ok=True)
    mv = MlflowClient().get_model_version(model_name, version.version)
    mlflow.artifacts.download_artifacts(artifact_uri=version.uri, dst_path=str(out / MODEL))
    sig = Path(mlflow.artifacts.download_artifacts(artifact_uri=mv.tags["signature"], dst_path=str(out / ".sig")))
    shutil.move(str(sig), out / SIGNATURE)
    shutil.rmtree(out / ".sig")
    if "mlbom" in mv.tags:
        bom = Path(mlflow.artifacts.download_artifacts(artifact_uri=mv.tags["mlbom"], dst_path=str(out / ".bom")))
        shutil.move(str(bom), out / MLBOM)
        shutil.rmtree(out / ".bom")
    else:
        (out / MLBOM).write_text("{}\n")
    (out / RELEASE).write_text(json.dumps({"name": model_name, "version": version.version,
                                           "run_id": mv.tags.get("run_id", "")}, indent=2) + "\n")
    (out / "Dockerfile").write_text(DOCKERFILE)
    return out
