"""Rendered manifests for GitOps delivery (gate G6): what Argo CD applies is exactly what is committed.

Promoting a model is a pull request that changes an environment's release: the ticket-router chart rendered with
that environment's values (deploy/gitops/envs/<env>/values.yaml) and the model and server images by digest.
Reviewers see the exact objects and digests that will run, Argo CD syncs only merged commits, and Kyverno still verifies signatures at admission, so even a merged change cannot run an
unsigned image. Only images from the cluster's registry (deploy/versions.env), pinned by digest, are accepted here,
which is the same rule the require-registry-and-digest policy enforces.

On the CI cluster there is no pull request to merge, so the release travels as an OCI artifact in the cluster
registry instead of a git commit. ci_argocd() derives that Application and its project from the committed ones,
changing only where the source comes from: the destination, the allowed kinds and the sync policy CI exercises are
exactly the ones production uses.
"""
from __future__ import annotations

import copy
import re
from pathlib import Path

import yaml

from . import helm

ROOT = Path(__file__).resolve().parents[1]
CHART = ROOT / "charts" / "ticket-router"          # the namespace is not in it: the platform owns the namespace
ENVS = ROOT / "deploy" / "gitops" / "envs"
ENV = re.compile(r"^[a-z][a-z0-9-]{0,30}$")
RENDERED = ROOT / "deploy" / "gitops" / "rendered"     # what the ApplicationSet syncs, one directory per environment
DIGEST = re.compile(r"^(?P<registry>[a-z0-9.-]+(:[0-9]+)?)(/[a-z0-9._-]+)+@sha256:[0-9a-f]{64}$")


ARGOCD = ROOT / "deploy" / "gitops" / "argocd" / "ticket-router.yaml"
OCI_SOURCE = re.compile(r"^oci://(?P<registry>[a-z0-9.-]+(:[0-9]+)?)(/[a-z0-9._-]+)+$")
TAG = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]{0,127}$")


class ReleaseError(ValueError):
    pass


def cluster_registry() -> str:
    for line in (ROOT / "deploy" / "versions.env").read_text().splitlines():
        if line.startswith("REGISTRY="):
            return line.split("=", 1)[1].strip()
    raise ReleaseError("deploy/versions.env names no REGISTRY")


def check_image(ref: str, what: str) -> None:
    match = DIGEST.fullmatch(ref)
    if not match:
        raise ReleaseError(f"{what} must be pinned by digest (registry/repository@sha256:...), got {ref!r}")
    if match["registry"] != cluster_registry():
        raise ReleaseError(f"{what} must come from the cluster registry {cluster_registry()}, got {ref!r}")


def release_dir(env: str) -> Path:
    """Where an environment's release is committed, and where its Argo CD Application reads it from."""
    return RENDERED / env


def render(model_image: str, server_image: str, out_dir: str | Path, env: str = "prod") -> list[Path]:
    """Render the chart for one environment and write its release to out_dir, one file per kind; returns the files
    written, kustomization.yaml last."""
    check_image(model_image, "the model image")
    check_image(server_image, "the server image")
    values, target = ENVS / env / "values.yaml", ENVS / env / "target.yaml"
    if not ENV.fullmatch(env) or not values.is_file() or not target.is_file():
        known = ", ".join(sorted(p.name for p in ENVS.iterdir() if (p / "values.yaml").is_file()))
        raise ReleaseError(f"no environment {env!r}; environments are {known}")
    try:
        text = helm.template(CHART, [values], {"model.image": model_image, "server.image": server_image})
    except helm.HelmError as exc:
        raise ReleaseError(f"the chart did not render for {env}: {exc}") from None
    by_file: dict[str, list[dict]] = {}
    for doc in yaml.safe_load_all(text):
        if doc:
            by_file.setdefault(f"{doc['kind'].lower()}.yaml", []).append(doc)
    chart = yaml.safe_load((CHART / "Chart.yaml").read_text())
    source = f"charts/ticket-router {chart['version']} with deploy/gitops/envs/{env}/values.yaml"
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name in sorted(by_file):
        body = yaml.safe_dump_all(by_file[name], sort_keys=False)
        (out / name).write_text(f"# Generated by `smlops render-release --env {env}` from {source};\n"
                                f"# edit those, not this file.\n" + body)
        written.append(out / name)
    kustomization = ("# Generated by `smlops render-release`. Argo CD syncs this directory; a pull request that\n"
                     "# changes it is a promotion.\n"
                     "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n"
                     "commonAnnotations:\n"
                     f"  smlops.io/environment: {env}\n"
                     f"  smlops.io/chart: \"ticket-router-{chart['version']}\"\n"
                     f"  smlops.io/model-image: \"{model_image}\"\n"
                     f"  smlops.io/server-image: \"{server_image}\"\n"
                     "resources:\n" + "".join(f"  - {p.name}\n" for p in written))
    (out / "kustomization.yaml").write_text(kustomization)
    # Where it runs, for the ApplicationSet; not a manifest, so the kustomization does not list it.
    (out / "target.yaml").write_text(target.read_text())
    return [*written, out / "kustomization.yaml"]


def ci_argocd(source: str, revision: str) -> list[dict]:
    """The committed AppProject and Application, with the release read from an OCI artifact in the cluster registry
    (oci://registry/repository at tag `revision`) instead of git."""
    match = OCI_SOURCE.fullmatch(source)
    if not match or match["registry"] != cluster_registry():
        raise ReleaseError(f"the CI source must be oci://{cluster_registry()}/..., got {source!r}")
    if not TAG.fullmatch(revision):
        raise ReleaseError(f"not an OCI tag: {revision!r}")
    project, app = (copy.deepcopy(d) for d in yaml.safe_load_all(ARGOCD.read_text()) if d)
    project["spec"]["sourceRepos"] = [source]
    app["spec"]["source"] = {"repoURL": source, "targetRevision": revision, "path": "."}
    return [project, app]
