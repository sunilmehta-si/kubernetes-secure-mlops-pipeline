"""Rendered manifests for GitOps delivery (gate G6): what Argo CD applies is exactly what is committed.

Promoting a model is a pull request that changes deploy/gitops/production/: the serving templates in deploy/serving/
with the model and server images filled in by digest. Reviewers see the exact digests that will run, Argo CD syncs
only merged commits, and Kyverno still verifies signatures at admission, so even a merged change cannot run an
unsigned image. Only images from the cluster's registry (deploy/versions.env), pinned by digest, are accepted here,
which is the same rule the require-registry-and-digest policy enforces.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TEMPLATES = ROOT / "deploy" / "serving"
# template file -> the placeholder it carries; the other files are copied as they are
FILLED = {"servingruntime.yaml": "SERVER_IMAGE", "inferenceservice.yaml": "MODEL_IMAGE"}
COPIED = ("networkpolicy.yaml", "serviceaccount.yaml")    # not namespace.yaml: the platform owns the namespace
DIGEST = re.compile(r"^(?P<registry>[a-z0-9.-]+(:[0-9]+)?)(/[a-z0-9._-]+)+@sha256:[0-9a-f]{64}$")
PLACEHOLDER = re.compile(r"\$\{[A-Z_]+\}")


class ReleaseError(ValueError):
    pass


def cluster_registry() -> str:
    for line in (ROOT / "deploy" / "versions.env").read_text().splitlines():
        if line.startswith("REGISTRY="):
            return line.split("=", 1)[1].strip()
    raise ReleaseError("deploy/versions.env names no REGISTRY")


def check_image(ref: str, what: str) -> None:
    match = DIGEST.fullmatch(ref)
    if not match:
        raise ReleaseError(f"{what} must be pinned by digest (registry/repository@sha256:...), got {ref!r}")
    if match["registry"] != cluster_registry():
        raise ReleaseError(f"{what} must come from the cluster registry {cluster_registry()}, got {ref!r}")


def render(model_image: str, server_image: str, out_dir: str | Path) -> list[Path]:
    """Write the production manifests to out_dir and return the files written, kustomization.yaml last."""
    check_image(model_image, "the model image")
    check_image(server_image, "the server image")
    values = {"MODEL_IMAGE": model_image, "SERVER_IMAGE": server_image}
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name in sorted((*FILLED, *COPIED)):
        text = (TEMPLATES / name).read_text()
        if name in FILLED:
            text = text.replace("${" + FILLED[name] + "}", values[FILLED[name]])
        left = PLACEHOLDER.findall(text)
        if left:
            raise ReleaseError(f"deploy/serving/{name} still has {', '.join(sorted(set(left)))} after rendering")
        header = (f"# Generated by `smlops render-release` from deploy/serving/{name}; edit the template, not this "
                  f"file.\n")
        (out / name).write_text(header + text)
        written.append(out / name)
    kustomization = ("# Generated by `smlops render-release`. Argo CD syncs this directory; a pull request that\n"
                     "# changes it is a promotion.\n"
                     "apiVersion: kustomize.config.k8s.io/v1beta1\nkind: Kustomization\n"
                     "commonAnnotations:\n"
                     f"  smlops.io/model-image: \"{model_image}\"\n"
                     f"  smlops.io/server-image: \"{server_image}\"\n"
                     "resources:\n" + "".join(f"  - {p.name}\n" for p in written))
    (out / "kustomization.yaml").write_text(kustomization)
    return [*written, out / "kustomization.yaml"]
